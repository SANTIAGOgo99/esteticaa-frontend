const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PWA_PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const evidence = path.join(root, 'docs', 'connectivity-evidence');
fs.mkdirSync(evidence, { recursive: true });
const remote = process.env.PWA_TEST_URL;
let server, browser;
(async () => {
  if (!remote) {
    const dist = path.join(root, 'dist');
    server = http.createServer((req, res) => {
      let file = path.join(dist, decodeURI(req.url.split('?')[0]));
      if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(dist, 'index.html');
      res.setHeader('Content-Type', { '.js': 'application/javascript', '.css': 'text/css', '.html': 'text/html', '.png': 'image/png', '.svg': 'image/svg+xml', '.webmanifest': 'application/manifest+json' }[path.extname(file)] || 'application/octet-stream');
      res.end(fs.readFileSync(file));
    });
    await new Promise(resolve => server.listen(5174, '127.0.0.1', resolve));
  }
  const base = remote || 'http://localhost:5174';
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: 'allow' });
  const page = await context.newPage();
  const status = page.getByRole('status').filter({ hasText: /En línea|Sin conexión a Internet|Conexión restablecida/ });
  await page.goto(base + '/catalogo');
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('article').length > 0);
  await page.waitForFunction(async () => (await (await caches.open('ec-public-v1')).keys()).length >= 2);
  const count = await page.locator('article').count();
  await status.filter({ hasText: 'En línea' }).waitFor();
  await context.setOffline(true);
  await status.filter({ hasText: 'Sin conexión a Internet' }).waitFor();
  await page.screenshot({ path: path.join(evidence, 'offline.png'), fullPage: true });
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('article').length > 0);
  assert.equal(await page.locator('article').count(), count);
  await context.setOffline(false);
  await status.filter({ hasText: 'Conexión restablecida' }).waitFor();
  await page.screenshot({ path: path.join(evidence, 'online.png'), fullPage: true });
  await page.getByRole('link', { name: 'Inicio', exact: true }).click();
  await page.waitForURL(base + '/');
  await context.setOffline(true);
  await status.filter({ hasText: 'Sin conexión a Internet' }).waitFor();
  assert(await status.isVisible());
  const box = await status.boundingBox();
  assert(box && box.y >= 0 && box.y + box.height <= 900);
  await page.screenshot({ path: path.join(evidence, 'inicio-offline.png'), fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + '/catalogo');
  await status.filter({ hasText: 'Sin conexión a Internet' }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(evidence, 'movil-offline.png'), fullPage: false });
  const results = { base, publicItems: count, shellOffline: true, catalogsOffline: true, offlineMessage: true, onlineRecoveryMessage: true, homeLink: true, messageVisibleAboveNavbar: true, mobileNoOverflow: true };
  fs.writeFileSync(path.join(evidence, 'results.json'), JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); if (server) server.close(); });
